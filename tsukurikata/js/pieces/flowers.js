  // 1番かっこ：低音が A#→B→C→C# と上がり、最後の小節は sf の8分音符のあと f で上行して B の頭へ
  const B_E = 'G5:2 D5 | G5:2 D#5 | G5:2 E5 | A5:.5> A4:.5 B4:.5 C#5:.5 D5:.5 E5:.5';
