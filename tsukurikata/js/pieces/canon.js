'use strict';
/* ===== 自由曲：パッヘルベル「カノン」（3つのヴァイオリンと通奏低音のためのカノン ニ長調）=====
   実音のまま。1拍＝8分音符（原曲の4分の4拍子の1小節が8拍）。32分音符まで出てくるので、8分音符を1拍に数える。
   低音が2小節で8つの音（D A H Fis G D G A）を何度もくり返し（グラウンド・バス）、その上で3つのヴァイオリンが
   2小節ずつ遅れて同じ旋律を追いかける（厳密なカノン）。
   楽譜は、ベルリン国立図書館の手稿の写し（Mus.ms. 16481/8、1838〜42年ごろ。パブリックドメイン、IMSLP #346264）と、
   ザイフェルト校訂の総譜（Kistner & Siegel 1929年、Organum III-24。パブリックドメイン、IMSLP #44549）を1小節ずつ読んだ。
   音はどちらも同じ。手稿には強弱・スラー・トリルが書かれていないので、それらはザイフェルト版に合わせた。
   使う部分：原曲の1〜14小節（低音だけ → 4分音符 → 8分音符 → 16分音符）と、19〜22小節（32分音符のいちばん有名なところ）。
   15〜18小節は、全部の声部をそろえて飛ばす（どの瞬間も、3つの声部の重なりは原曲のどこかと同じになる）。
   終わりは原曲の最後の小節にならって、主和音をのばして終える（原曲は4分音符で終わる） */
{
  // 第1ヴァイオリンが2小節ずつ受け持つ旋律（原曲の小節番号）。第2・第3ヴァイオリンは、これを2小節・4小節遅れて弾く
  const d16 = s => s.split(' ').map(t => t.replace(/^([^:'>~*]+)(['>~*]*)$/, '$1:.5$2')).join(' ');
  const d32 = s => s.split(' ').map(t => t.replace(/^([^:'>~*]+)(['>~*]*)$/, '$1:.25$2')).join(' ');
  const U = [null,
    'F#5:2 E5:2 D5:2 C#5:2 | B4:2 A4:2 B4:2 C#5:2',                                  // 3〜4小節：4分音符
    'D5:2 C#5:2 B4:2 A4:2 | G4:2 F#4:2 G4:2 E4:2',                                    // 5〜6小節
    'D4 F#4 A4 G4 F#4 D4 F#4 E4 | D4 B3 D4 A4 G4 B4 A4 G4',                           // 7〜8小節：8分音符
    // 10小節目の付点8分音符のトリルは、手稿にはなくザイフェルト版にある（終止の前の決まった飾り）
    'F#4 D4 E4 C#5 D5 F#5 A5 A4 | B4 G4 A4 F#4 D4 D5 D5:1.5~ C#5:.5',                // 9〜10小節
    d16('D5 C#5 D5 D4 C#4 A4 E4 F#4 D4 D5 C#5 B4 C#5 F#5 A5 B5') + ' | ' +           // 11〜12小節：16分音符
      d16('G5 F#5 E5 G5 F#5 E5 D5 C#5 B4 A4 G4 F#4 E4 G4 F#4 E4'),
    d16('D4 E4 F#4 G4 A4 E4 A4 G4 F#4 B4 A4 G4 A4 G4 F#4 E4') + ' | ' +              // 13〜14小節
      d16('D4 B3 B4 C#5 D5 C#5 B4 A4 G4 F#4 E4 B4 A4 B4 A4 G4'),
    // 15〜18小節（第1ヴァイオリンの分は飛ばす。第2・第3ヴァイオリンが19〜22小節で弾く）。スタッカートはザイフェルト版のもの
    "F#4 F#5' E5:2 r D5 F#5:2 | B5:2 A5:2 B5:2 C#6:2",
    "D6' D5' C#5:2 r B4 D5:2 | D5:3 D5 D5 G5 E5 A5",
    // 19〜22小節：16分音符と2つの32分音符、32分音符の駆け上がり。跳ぶ前の音のスタッカートはザイフェルト版のもの
    'A5:.5 F#5:.25 G5:.25 A5:.5 F#5:.25 G5:.25 ' + d32("A5' A4 B4 C#5 D5 E5 F#5 G5") + " F#5:.5 D5:.25 E5:.25 F#5:.5' F#4:.25 G4:.25 " + d32('A4 B4 A4 G4 A4 F#4 G4 A4') + ' | ' +
      'G4:.5 B4:.25 A4:.25 G4:.5 F#4:.25 E4:.25 ' + d32('F#4 E4 D4 E4 F#4 G4 A4 B4') + ' G4:.5 B4:.25 A4:.25 B4:.5 C#5:.25 D5:.25 ' + d32('A4 B4 C#5 D5 E5 F#5 G5 A5'),
    'F#5:.5 D5:.25 E5:.25 F#5:.5 E5:.25 D5:.25 ' + d32('E5 C#5 D5 E5 F#5 E5 D5 C#5') + " D5:.5 B4:.25 C#5:.25 D5:.5' D4:.25 E4:.25 " + d32('F#4 G4 F#4 E4 F#4 D5 C#5 D5') + ' | ' +
      'B4:.5 D5:.25 C#5:.25 B4:.5 A4:.25 G4:.25 ' + d32('A4 G4 F#4 G4 A4 B4 C#5 D5') + ' B4:.5 D5:.25 C#5:.25 D5:.5 C#5:.25 B4:.25 ' + d32('C#5 D5 E5 D5 C#5 D5 B4 C#5'),
  ];
  // ゲームの2小節ごとに、原曲のどの2小節を使うか（0＝低音だけの1〜2小節。原曲の15〜18小節は飛ばす）
  const ORIG = [0, 1, 2, 3, 4, 5, 6, 9, 10];
  // 声部 v（0＝第1ヴァイオリン）の線：原曲で v×2小節遅れて弾く旋律を、ゲームの小節に並べる。最後は主和音の音をのばす
  const voice = (v, last) => [...ORIG.flatMap((o, g) => o - v >= 1 ? line(U[o - v], g * 16) : []), ...line(last, 144)];
  const CN_MEL = voice(0, 'D5:8');
  const CN_BASS = line(rep('D3:2 A2:2 B2:2 F#2:2 | G2:2 D2:2 G2:2 A2:2', 9) + ' | D3:8');
  const CN_CH = chords(rep('D:2 A:2 Bm:2 F#m:2 | G:2 D:2 G:2 A:2', 9) + ' | D:8');

  // 強弱：手稿には書かれていない。ザイフェルト版（低音だけのところは mf、第1ヴァイオリンが p espr. で入り、9小節目から cresc.、
  // 11小節目で mf、13小節目で mp、19小節目からまた mf）に合わせ、終わりの2小節（ここで足した終わり方）で f へ
  const CN_DYN = [[0,.5],[15.9,.48],[16,.42],[24,.45],[31.9,.43],[32,.43],[40,.45],[44,.44],[47.9,.42],[48,.43],[56,.46],[63.9,.47],
    [64,.47],[72,.52],[79.9,.57],[80,.6],[88,.65],[95.9,.58],[96,.53],[104,.55],[111.9,.56],
    [112,.62],[120,.65],[127.9,.62],[128,.62],[136,.66],[143.9,.74],[144,.78],[152,.78]];

  /* 吹奏楽の席への移し方
     3つの声部が同じ旋律を追いかけるのが聞こえるよう、声部ごとに音色と高さの違う組に分けた。
     第1ヴァイオリン（いつも新しい旋律を先に出す）→ 旋律：クラ1st・アルト1st・フルート（8分音符からはフルートは1オクターブ上。
       16分音符からフルート2nd、最後の32分音符のところはピッコロ（1オクターブ上）・E♭クラ（同じ高さ）も重ねる）
     第2ヴァイオリン → オーボエ・クラ2nd・アルト2nd・トランペット1st（同じ高さ）
     第3ヴァイオリン → クラ3rd（同じ高さ）、テナー・ホルン1st・2nd（1オクターブ下。ホルンは原曲の高さでは吹けない）
     原曲では3つのヴァイオリンが同じ重さなので、全員の部では3つの声部がほぼ同じ大きさになるよう、人数の多い第1声部（クラ1st は3人）を控えめにした。
     少人数の部（アルト1st・トランペット1st・ホルン1st・ユーフォ・チューバ）でも、アルト・トランペット・ホルンの3つの音色で3つの声部がそろう。
     アルトは B5・D6 が出せないので、それが出てくるところ（1st は2小節、2nd は4小節）だけ1オクターブ下で吹く。トランペットの D6（第2声部の原曲17小節の頭）と、
       ユーフォ・弦バス・バストロのいちばん低い D は、その音だけ1オクターブ移る。
     通奏低音の低音（チェロとヴィオローネ）→ ユーフォ・ファゴット・バスクラ・バリトン（同じ高さ）、チューバ・弦バス（1オクターブ下）。
       バストロンボーンは16分音符のところから1オクターブ下で重ねる。
     通奏低音の和音（原曲ではチェンバロが弾く。ザイフェルト版の和音づけと同じ D A Hm Fism G D G A）→ マリンバの4分音符の和音と、
       ホルン3rd・4th・トロンボーンの小さなのばす和音。ホルン1st・2nd も、第3ヴァイオリンが入るまでは和音を吹く。
       トランペット2nd・3rd は32分音符のところから和音に加わる（原曲にはない）。
     打楽器（ティンパニ・小太鼓など）は原曲にないので使わない */
  const CN_CEMB = (() => {
    const vs = voiceGroup(CN_CH, 3, 61, 71);
    return CN_CH.flatMap((c, k) => vs[k].map(m => ({i: 'mrb', b: c.b, m, v: .02 + .18 * interp(CN_DYN, c.b)})));
  })();

  addPiece({
    id: 'canon',
    title: '「カノン」',
    full: 'パッヘルベル「カノン」（3つのヴァイオリンと通奏低音のためのカノン ニ長調）',
    composer: 'J.パッヘルベル（1680年ごろ）',
    key: 'ニ長調', trans: 0, meter: 8, beatUnit: .5, beats: 152,
    // 原曲に速さの指定はない。ザイフェルト版の Sostenuto ♩=56（8分音符で112）を「標準」にした
    tempi: [100, 112, 124],
    desc: '結婚式でもおなじみの曲。低音が同じ8つの音を何度もくり返す上で、3つのグループが同じ旋律を2小節ずつ遅れて追いかける。ゆっくりした音から、だんだん細かい音へ。3つの旋律がどれも聞こえるか、低音の歩みが最後まで乱れないかが問われる。',
    asks: 'バランス・リズム・音程',
    focus: {pitch: 1.1, tone: 1, expr: .95, rhythm: 1.1, balance: 1.1},
    balRef: -2.15, ceiling: .98,
    spans: [{name: 'はじまり（ゆったりした旋律）', short: 'はじまり', from: 0, to: 64}, {name: '中ほど（16分音符で細かく）', short: '中ほど', from: 64, to: 112},
      {name: '後半（いちばん有名な細かい旋律）', short: '後半', from: 112, to: 152}],
    // 4分音符・8分音符は1音ずつ（弓を返すように）、16分音符・32分音符はつなげて吹く
    slur: 'pairs',
    scale: [[0, [1, 2, 4, 6, 7, 9, 11]]],
    mel: CN_MEL,
    chords: CN_CH,
    bass: CN_BASS,
    lines: {v2: voice(1, 'F#5:8'), v3: voice(2, 'A4:8')},
    dyn: CN_DYN,
    // テンポは原曲では変わらない。ここで足した終わりの2小節だけ、ゆるめて和音をのばす
    rubato: [[0,1],[134,1],[140,1.06],[143.9,1.15],[144,1.25],[152,1.6]],
    groups: {
      cont: {n: 4, lo: 50, hi: 67, rh: 'sus'},
      top: {n: 2, lo: 62, hi: 74, rh: 'sus'},
    },
    roles: {
      // 第1声部（第1ヴァイオリン）
      fl1:   [{f: 16, t: 48, r: 'mel', sh: 0, sc: .75}, {f: 48, t: 152, r: 'mel', sh: 12, sc: .6}],
      fl2:   [{f: 80, t: 152, r: 'mel', sh: 12, sc: .5}],
      picc:  [{f: 112, t: 152, r: 'mel', sh: 12, sc: .35}],
      ebcl:  [{f: 112, t: 152, r: 'mel', sh: 0, sc: .45}],
      cl1:   [{f: 16, t: 152, r: 'mel', sh: 0, sc: .8}],
      // アルトは B5 が出せないので、それが出てくる16分音符の2小節（原曲の11〜12小節）だけ1オクターブ下で
      asax1: [{f: 16, t: 80, r: 'mel', sh: 0}, {f: 80, t: 96, r: 'mel', sh: -12}, {f: 96, t: 152, r: 'mel', sh: 0}],
      // 第2声部（第2ヴァイオリン）。トランペット1st がいない部では、ほかの第2声部の人、和音の人、第1声部を重ねている人の順に受け持つ
      ob:    [{f: 32, t: 152, r: 'cm', line: 'v2', sh: 0}],
      cl2:   [{f: 32, t: 152, r: 'cm', line: 'v2', sh: 0}],
      asax2: [{f: 32, t: 96, r: 'cm', line: 'v2', sh: 0, sc: .9}, {f: 96, t: 128, r: 'cm', line: 'v2', sh: -12, sc: .9}, {f: 128, t: 152, r: 'cm', line: 'v2', sh: 0, sc: .9}],
      tp1:   [{f: 32, t: 152, r: 'cm', line: 'v2', sh: 0, sc: .85, fb: ['cl2', 'asax2', 'ob', 'fl2', 'tp2', 'tp3', 'ebcl', 'cl1', 'fl1']}],
      // 第3声部（第3ヴァイオリン）。ホルン1st がいない部では、テナー・クラ3rd・ほかのホルン・トロンボーン、最後はユーフォが受け持つ
      cl3:   [{f: 48, t: 152, r: 'cm', line: 'v3', sh: 0}],
      tsax:  [{f: 48, t: 152, r: 'cm', line: 'v3', sh: -12, sc: .9}],
      hn1:   [{f: 0, t: 48, r: 'pad', g: 'cont', i: 1, sc: .9}, {f: 48, t: 152, r: 'cm', line: 'v3', sh: -12, sc: .9, fb: ['tsax', 'cl3', 'hn2', 'hn3', 'hn4', 'tb1', 'tb2', 'euph']}],
      hn2:   [{f: 0, t: 48, r: 'pad', g: 'cont', i: 2, sc: .9}, {f: 48, t: 152, r: 'cm', line: 'v3', sh: -12, sc: .8}],
      // 通奏低音の和音
      hn3:   [{f: 0, t: 152, r: 'pad', g: 'cont', i: 0}],
      hn4:   [{f: 0, t: 152, r: 'pad', g: 'cont', i: 1}],
      tb1:   [{f: 0, t: 152, r: 'pad', g: 'cont', i: 2, sc: .9}],
      tb2:   [{f: 0, t: 152, r: 'pad', g: 'cont', i: 3, sc: .9}],
      tp2:   [{f: 112, t: 152, r: 'pad', g: 'top', i: 0, sc: .8}],
      tp3:   [{f: 112, t: 152, r: 'pad', g: 'top', i: 1, sc: .8}],
      // 通奏低音の低音
      euph:  [{f: 0, t: 152, r: 'bass', sh: 0, sc: .75}],
      fg:    [{f: 0, t: 152, r: 'bass', sh: 0, sc: .75}],
      bcl:   [{f: 0, t: 152, r: 'bass', sh: 0, sc: .65}],
      bsax:  [{f: 0, t: 152, r: 'bass', sh: 0, sc: .55}],
      tuba:  [{f: 0, t: 152, r: 'bass', sh: -12, sc: .55}],
      cb:    [{f: 0, t: 152, r: 'bass', sh: -12, sc: .6}],
      btb:   [{f: 64, t: 152, r: 'bass', sh: -12, sc: .5}],
    },
    perc: {
      // チェンバロの右手の和音（マリンバ）
      perc3: CN_CEMB,
    },
    // 解釈（テンポ・揺れ）が部の実力に合っているか。当てはまるものを [点の増減, 講評] で返す
    interpRules: (perf, ip) => [
      ip.tempo === 2 && perf.bandR < 0.72 && [-3, '速いテンポで細かい音がそろわず、3つの旋律の追いかけっこがくずれました。'],
      ip.tempo === 0 && perf.bandE < 0.6 && [-2, 'ゆっくりしたテンポを支えきれず、音楽が止まりそうに聞こえます。'],
      ip.rub === 2 && [-3, '低音が同じ歩みで進む曲なのに、テンポを揺らしすぎました。'],
    ],
  });
}
