  // 低音（コントラバスの楽譜の高さで書く。チューバ・コントラバスは1オクターブ下で鳴る）。A は1・3拍目に4分音符、B は4分音符で歩く
  const BS_A = 'Ab2 r Bb2 | G2 r G2 | Ab2 r Bb2 | C3:2 Bb2 | Ab2 r Bb2 | G2 r Eb2:.5 G2:.5 | Ab2 r C3';
  const BS_B = 'Bb3 r C4 | D4 r G2 | Bb2 r Eb3 | Ab3 G3 F3 | C4 Bb3 Ab3 | G3 F3 Eb3 | Ab3 F3 Eb3 | D3 C3 Bb2';
