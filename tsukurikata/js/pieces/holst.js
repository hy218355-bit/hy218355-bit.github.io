    tpI: line('Bb4 | Bb4 r Eb5 | Bb4 r Eb5 | D5 r Eb5', B(24) + 2),
    tpII: line('Bb3 | Bb3 r Eb4 | Bb3 r Eb4 | D4 r Eb4 | Eb4:2', B(24) + 2),
