  const W_FG = 'X Q Q Q H Q Q Q R Q Q Q D';     // 0〜12小節目のファゴット（4小節目は2分音符）
  const HP = 'Q Q Q Q Q Q Q R ' + 'Q '.repeat(15) + 'R ' + 'Q '.repeat(15) + 'F';   // 1〜40小節目のハープ
  const HN_A = 'Q Q Q H Q Q Q d';               // 17〜24小節目のホルン
  const BR_F = 'T Qa Qa Qa Ha Qa Qa Qa F';      // 32〜40小節目のトランペット・トロンボーン
  const mel = (f, t, sh, sc) => ({f, t, r: 'mel', sh, ...(sc ? {sc} : {})});
  const cm = (ln, f, t, sh = 0, sc) => ({f, t, r: 'cm', line: ln, sh, ...(sc ? {sc} : {})});
  const bass = (f, t, sh, opt = {}) => ({f, t, r: 'bass', sh, ...opt});
  // ホルン：A・B は旋律、13〜16小節目は和音の動き、A' は1・3拍目の和音、2回目は29小節目から和音の動き、32小節目の3拍目から旋律（低い音で）
  // 1回目は旋律を重ねる人が多いので、3rd・4th は少し控えめに
