    ...at(JU_B, B(9)), ...at('G4:.5 Bb4:.5', B(16) + 2),            // B
    ...at(JU_A, B(17), 1), ...at('Eb5:2 Bb5:.5 G5:.5', B(24)),     // A'（1オクターブ上）
    ...at(JU_B, B(25), 1), ...at('G5:.5 Bb5:.5', B(32) + 2),        // 2回目の B
    ...at(JU_A, B(33), 2), ...at('Eb6:3', B(40)),                   // 2回目の A（終わりは E♭）
