'use strict';
/* ===== 自由曲4：エルガー 行進曲「威風堂々」第1番より 中間部 =====
   ト長調、実音のまま。1拍＝4分音符、2/4拍子。前半はトリオの1回目（やわらかく）、後半は曲の終わりの全合奏（1オクターブ上で全員で）。
   旋律・和音・低音は PDMX（CC0）のオルガン譜から写した */
{
  const POMP_A = 'G4:2 | F#4:.5 G4:.5 A4:1 | E4:2 | D4:2 | C4:2 | B3:.5 C4:.5 D4:1 | A3:4 | B3:2 | C#4:.5 D4:1 E4:.5 | A4:2 | D4:2';
  // 終わりの4小節は、原曲の5小節（旋律の音を2小節のばし、2小節で終わりの形になって、次の部分の頭に着く）を、ここで曲が終わるように縮めてある
  const POMP_MEL = [...line(POMP_A + ' | G4:2.5 F#4:1 E4:.5 | D4:4'), ...shift(oct(line(POMP_A), 1), 32),
    ...line('C6:2 | C6:.5 B5:1 A5:.5 | B5:4 | E5:2 | F#5:.5 G5:1 A5:.5 | D5:2 | G5:2 | G4:2 | C5:.5 B4:1 A4:.5 | G4:4', 56)];
  const POMP_CH = 'G:2 | D7/A:2 | Em/B:2 | G/B:2 | C:2 | G/D:2 | A7/E:2 | D:2 | G:2 | A7/G:2 | D/F#:2 | G:2 | Em7:2 | A7:2 | D:2 | D7:2 | '
    + 'G:2 | D7/A:2 | Em/B:2 | G/B:2 | C/E:2 | G/D:2 | A7/C#:2 | D:2 | G:2 | A7/G:2 | D/F#:2 | D/F#:2 | C/E:2 | D:1 D7:1 | G:2 | G:1 G7:1 | C:2 | D7/A:2 | G:2 | Em:2 | Am7:2 | D7:2 | G:4';

  /* 楽器の受け持ちは、エルガーのオーケストラ総譜（Boosey & Co. 1902年の初版を Dover が復刻したもの。パブリックドメイン、IMSLP #24159）を
     読んで、吹奏楽の席に移した。前半はトリオ（Largamente）の最初の16小節、後半は曲の終わりの Molto Maestoso の後半16小節＋終わり
     （原曲ではニ長調なので、ト長調に移して読んだ）。
     ・トリオの1回目：旋律は第1ヴァイオリン（G線で）・クラリネット2人・ホルン4人が同じ高さで歌う。第2ヴァイオリン・ヴィオラ・ファゴット・ハープ・
       ティンパニは4分音符を軽く刻み、チェロとコントラバスも4分音符で低音を刻む。すべて p。
       → 旋律はクラ1st・2nd、ホルン4人、アルト1st（第1ヴァイオリン）。ユーフォニアムは、吹奏楽でよくあるように旋律を1オクターブ下でなぞる
         （少人数の部でも旋律が聞こえるように）。刻みはクラ3rd・アルト2nd・テナー（第2ヴァイオリン・ヴィオラ）とファゴット、ハープはマリンバへ。
         低音の刻みは弦バス・チューバ（コントラバス）、バスクラ・バリトンサックス（コントラファゴット）
     ・全合奏：旋律はピッコロ・フルート・オーボエ・クラリネット（2オクターブ）・トランペット・コルネット・第1ヴァイオリン・チェロ。
       ホルン・トロンボーン・ファゴット・第2ヴァイオリン・ヴィオラ・ハープは、アクセントつきの4分音符で和音を刻む。
       コントラバス・チューバ・3番トロンボーンも4分音符で低音を刻み、オルガンの足鍵盤（16・32フィート）が長い低音をのばす。
       大太鼓とシンバル・スネア（前打音つき）・ティンパニは毎拍打つ。
       → 旋律は木管・アルト1st・テナー・トランペット1st/2nd・ユーフォニアム（チェロ）。山場の2小節はホルン1st・2nd も旋律へ。
         刻みはホルン4人・トロンボーン・ファゴット・クラ3rd・アルト2nd・トランペット3rd。低音の刻みはバストロンボーン・チューバ・弦バス、
         オルガンの長い低音はバスクラとバリトンサックスがのばす */
  // 低音は4分音符で刻む（チェロ・コントラバス）。トリオの1回目は軽く（'）、全合奏ははっきり（>）。12小節目は総譜どおり B
  const qtr = (src, mk) => src.split('|').map(s => s.trim()).filter(Boolean)
    .map(s => { const [n, d] = s.split(':'); return Array(+d).fill(`${n}:1${mk}`).join(' '); }).join(' | ');
  const POMP_BASS = [
    ...line(qtr('G2:2 | A2:2 | B2:2 | B2:2 | C3:2 | D3:2 | E3:2 | D3:2 | G2:2 | G2:2 | F#2:2 | B2:2 | E2:2 | A2:2 | D3:2 | D3:2', "'")),
    ...line(qtr('G2:2 | A2:2 | B2:2 | B2:2 | E2:2 | D2:2 | C#3:2 | D3:2 | G2:2 | G2:2 | F#2:2 | F#2:2 | E2:2 | D2:2 | G2:2 | G2:2 | C3:2', '>')
      + ' | C3:1> A2:1> | ' + qtr('G2:2 | E2:2 | A2:2 | D2:2', '>') + ' | G2:4>', 32)];
  // オルガンの足鍵盤：小節をまたいで長くのばす低音（全合奏のところだけ）
  const POMP_PED = line('G2:2 | F#2:2 | B2:4 | E2:2 | D2:2 | C#2:2 | D2:2 | G2:4 | F#2:4 | E2:2 | D2:2 | G2:4 | C3:4 | G2:2 | E2:2 | A2:2 | D2:2 | G2:4', 32);

  // 伴奏の刻み方（1小節＝2拍）
  const QS = {pat: [[0, .6, 'norm'], [1, .6, 'norm']], len: 2};           // 4分音符を軽く切って（トリオの1回目。原曲は stacc.）
  const QA = {pat: [[0, 1, 'norm', true], [1, 1, 'norm', true]], len: 2};  // 4分音符をはっきり、アクセントつきで（全合奏）
  // 全合奏の区間：はじめ（G1）→ 山場の2小節（G2）→ 終わりまで（G3）→ 最後の和音（E）。区間ごとに和音の割りふりを決める
  const PS = {G1: [32, 56], G2: [56, 60], G3: [60, 76], E: [76, 80]};
  const rp = (g, sec, i, sc) => ({f: PS[sec][0], t: PS[sec][1], r: 'pad', g: g + (sec === 'E' ? 'E' : 'G'), i, ...(sc ? {sc} : {})});
  const rpAll = (g, i) => ['G1', 'G2', 'G3', 'E'].map(sec => rp(g, sec, i));
  // ホルン：1回目は4人とも旋律（3rd・4th は少し控えめに）。全合奏はアクセントつきの4分音符の和音を、ほかの刻みより少し強く（1st・2nd は山場だけ旋律）
  const pompHorn = i => [{f: 0, t: 32, r: 'mel', sh: 0, ...(i > 1 ? {sc: .7} : {})}, rp('hn', 'G1', i, 1.25),
    i < 2 ? {f: 56, t: 60, r: 'mel', sh: -12} : rp('hn', 'G2', i, 1.25), rp('hn', 'G3', i, 1.25), rp('hn', 'E', i, 1.25)];
  // ティンパニ（1回目）：G・D・A の3つを4分音符で軽く
  const POMP_TIMP = 'G G D D G G G G G G G G A A D D G G A A A A D D G G A A D D'.split(' ')
    .map((x, k) => ({i: 'timp', b: k, m: nn(x + (x === 'D' ? '3' : '2')), v: k % 2 ? .26 : .32}));
  // 全合奏の打楽器は毎拍。大太鼓とシンバルは2拍目を少し軽く、スネアは前打音（短いロール）をつけて
  const onBeats = (from, to, fn) => each(from, to, 1, b => fn(b, b % 2 === 0));

  addPiece({
    id: 'pomp',
    title: '「威風堂々」',
    full: 'エルガー 行進曲「威風堂々」第1番より（中間部）',
    composer: 'E.エルガー（1901年）',
    key: 'ト長調', trans: 0, meter: 2, beats: 80,
    tempi: [72, 80, 88],
    desc: '卒業式でおなじみの、あの堂々とした旋律。1回目は4分音符の静かな伴奏にのせてやわらかく、2回目は1オクターブ上で、打楽器も加わった全員で大きく歌い上げる。長い音を息で支える音色と、和音の響きが問われる。',
    asks: '音色・音程・バランス',
    focus: {pitch: 1.1, tone: 1.15, expr: 1.05, rhythm: .85, balance: 1.05},
    balRef: 6.6, ceiling: .98,
    spans: [{name: '1回目（やわらかく）', from: 0, to: 32}, {name: '2回目（全員で）', from: 32, to: 80}],
    slur: 'bar',
    scale: [[0, [0, 2, 4, 6, 7, 9, 11]]],
    mel: POMP_MEL,
    chords: chords(POMP_CH),
    bass: POMP_BASS,
    lines: {ped: POMP_PED},
    // 1回目はずっと p（10小節目で少しふくらみ、14小節目で少し引く）。16小節目は後半へのつなぎとして大きくしていく。
    // 全合奏は ff（17小節目に rf）、29小節目の山場へ向けてさらに大きく、終わりの手前でもう一度ふくらむ
    dyn: [[0,.36],[16,.38],[18,.44],[20,.4],[24,.42],[26,.44],[28,.38],[30,.42],[31.9,.72],[32,.96],[36,.92],[48,.92],[52,.95],[55.9,.98],[56,1],[64,1],[66,.94],[72,.94],[75.9,1],[80,1]],
    // 29小節目から allargando（だんだん遅く、堂々と）、34小節目から rit.、最後の和音はたっぷりのばす
    rubato: [[0,1],[13.5,1],[14,1.04],[16,1],[28,1],[30,1.06],[31.9,1.15],[32,1],[55,1],[56,1.08],[60,1.06],[64,1.02],[66,1.04],[72,1.1],[74,1.14],[76,1.25],[80,1.5]],
    groups: {
      inA: {n: 4, lo: 50, hi: 67, rh: QS},     // 1回目の刻み：クラ3rd・アルト2nd・テナー・ファゴット
      hpA: {n: 2, lo: 59, hi: 76, rh: QS},     // 1回目のハープ → マリンバ
      tbB: {n: 3, lo: 45, hi: 62, rh: 'sus'},  // 16小節目：トロンボーンの和音（原曲は pp。ここでは後半へのつなぎ）
      hnG: {n: 4, lo: 55, hi: 70, rh: QA}, hnE: {n: 4, lo: 55, hi: 70, rh: 'sus'},
      tbG: {n: 3, lo: 46, hi: 62, rh: QA}, tbE: {n: 3, lo: 46, hi: 62, rh: 'sus'},
      wG:  {n: 2, lo: 60, hi: 74, rh: QA}, wE:  {n: 2, lo: 60, hi: 74, rh: 'sus'},
      tpG: {n: 1, lo: 62, hi: 74, rh: QA}, tpE: {n: 1, lo: 62, hi: 74, rh: 'sus'},
    },
    roles: {
      picc:  [{f: 32, t: 80, r: 'mel', sh: 12, sc: .65}],
      fl1:   [{f: 32, t: 80, r: 'mel', sh: 0}],
      fl2:   [{f: 32, t: 80, r: 'mel', sh: 0, sc: .9}],
      ob:    [{f: 32, t: 80, r: 'mel', sh: 0}],
      ebcl:  [{f: 32, t: 80, r: 'mel', sh: 0, sc: .7}],
      // クラリネット：1回目は2人で旋律、全合奏は2オクターブに分かれて
      cl1:   [{f: 0, t: 80, r: 'mel', sh: 0}],
      cl2:   [{f: 0, t: 32, r: 'mel', sh: 0}, {f: 32, t: 80, r: 'mel', sh: -12}],
      cl3:   [{f: 0, t: 32, r: 'pad', g: 'inA', i: 0, sc: 1.3}, ...rpAll('w', 0)],
      // アルト1st は第1ヴァイオリン。全合奏ではコルネットと同じ高さで
      asax1: [{f: 0, t: 32, r: 'mel', sh: 0}, {f: 32, t: 80, r: 'mel', sh: -12}],
      asax2: [{f: 0, t: 32, r: 'pad', g: 'inA', i: 1, sc: 1.3}, ...rpAll('w', 1)],
      // テナーは1回目はヴィオラの刻み、全合奏はチェロと一緒に旋律
      tsax:  [{f: 0, t: 32, r: 'pad', g: 'inA', i: 2, sc: 1.3}, {f: 32, t: 80, r: 'mel', sh: -12}],
      bsax:  [{f: 0, t: 32, r: 'bass', sh: 0, sc: .7}, {f: 32, t: 80, r: 'bass', line: 'ped', sh: 0, sc: .85}],
      bcl:   [{f: 0, t: 32, r: 'bass', sh: 0, sc: .7}, {f: 32, t: 80, r: 'bass', line: 'ped', sh: 0, sc: .85}],
      fg:    [{f: 0, t: 32, r: 'pad', g: 'inA', i: 3, sc: 1.3}, ...rpAll('tb', 2)],
      hn1: pompHorn(0), hn2: pompHorn(1), hn3: pompHorn(2), hn4: pompHorn(3),
      // トランペット：1st・2nd はコルネットの旋律、3rd は和音を刻む（1回目は休み）
      tp1:   [{f: 32, t: 80, r: 'mel', sh: -12}],
      tp2:   [{f: 32, t: 80, r: 'mel', sh: -12, sc: .9}],
      tp3:   rpAll('tp', 0),
      tb1:   [{f: 30, t: 32, r: 'pad', g: 'tbB', i: 0, sc: .8}, ...rpAll('tb', 0)],
      tb2:   [{f: 30, t: 32, r: 'pad', g: 'tbB', i: 1, sc: .8}, ...rpAll('tb', 1)],
      btb:   [{f: 30, t: 32, r: 'pad', g: 'tbB', i: 2, sc: .8}, {f: 32, t: 76, r: 'bass', sh: 0, rh: 'march'}, {f: 76, t: 80, r: 'bass', sh: 0}],
      // ユーフォニアム：1回目は旋律を1オクターブ下で控えめに、全合奏はチェロと一緒に旋律を2オクターブ下で
      euph:  [{f: 0, t: 32, r: 'mel', sh: -12, sc: .75}, {f: 32, t: 80, r: 'mel', sh: -24}],
      tuba:  [{f: 0, t: 32, r: 'bass', sh: -12, sc: .8}, {f: 32, t: 76, r: 'bass', sh: -12, rh: 'march'}, {f: 76, t: 80, r: 'bass', sh: -12}],
      cb:    [{f: 0, t: 32, r: 'bass', sh: -12}, {f: 32, t: 76, r: 'bass', sh: -12, rh: 'march'}, {f: 76, t: 80, r: 'bass', sh: -12}],
      perc3: [{f: 0, t: 30, r: 'pad', g: 'hpA', i: 0, inst: 'mrb', sc: .6}, {f: 0, t: 30, r: 'pad', g: 'hpA', i: 1, inst: 'mrb', sc: .6}],
    },
    perc: {
      perc1: [
        ...POMP_TIMP,
        {i: 'timp', b: 30, d: 2, m: 50, roll: true, v: .25, v1: .75},
        ...timpOn(POMP_BASS, onBeats(32, 56, (b, one) => [[b, b === 32 ? .8 : one ? .55 : .45]])),
        {i: 'timp', b: 56, d: 2, m: 52, roll: true, v: .55, v1: .85},   // 29小節目：ロールでふくらむ
        ...timpOn(POMP_BASS, onBeats(58, 76, (b, one) => [[b, one ? .55 : .45]])),
        {i: 'timp', b: 76, d: 4, m: 43, roll: true, v: .6, v1: 1},
      ],
      perc2: [
        ...onBeats(32, 76, (b, one) => (b >= 56 && b < 58) || b >= 72 ? [] : [{i: 'sd', b: b - .15, d: .15, roll: true, v: .2, v1: .32}, {i: 'sd', b, v: one ? .5 : .42}]),
        {i: 'sd', b: 56, d: 2, roll: true, v: .4, v1: .65},     // 29小節目のロール
        {i: 'sd', b: 72, d: 4, roll: true, v: .3, v1: .75},     // 37〜38小節目：ロールでだんだん大きく
        {i: 'sd', b: 76, v: .85},
      ],
      perc3: [
        {i: 'bd', b: 30, d: 2, roll: true, v: .1, v1: .5},
        ...onBeats(32, 76, (b, one) => [{i: 'bd', b, v: b === 32 ? .75 : (b >= 56 && b < 60) ? (one ? .62 : .5) : one ? .5 : .4}]),
        {i: 'bd', b: 76, v: .9},
      ],
      perc4: [
        {i: 'sus', b: 30, d: 2, roll: true, v: .1, v1: .7},
        ...onBeats(32, 76, (b, one) => [{i: 'cym', b, v: b === 32 ? .9 : b === 56 ? .8 : one ? .38 : .28}]),
        {i: 'cym', b: 76, v: 1},
      ],
    },
    // 解釈（テンポ・揺れ）が部の実力に合っているか。当てはまるものを [点の増減, 講評] で返す
    interpRules: (perf, ip) => [
      ip.tempo === 2 && [-3, '急ぎ足に聞こえ、この旋律の堂々とした感じが出ていません。'],
      ip.rub === 0 && [-2, 'フレーズの終わりで、もう少し息をたっぷり使ってほしいところです。'],
    ],
  });
}
