  const RUNLO = sh => ({f: 30, t: 32, r: 'bass', line: 'runLo', sh});
  const CHROM = (sh, ln = 'chrom', t = 64) => ({f: 60, t, r: 'cm', line: ln, sh});
  // ホルン：1回目は4人とも旋律（3rd・4th は少し控えめに）。全合奏はアクセントつきの4分音符の和音を、ほかの刻みより少し強く。
  // 1st・2nd は山場だけ旋律、2nd・4th は31〜32小節目に半音で下がる線
  const pompHorn = i => [{f: 0, t: 32, r: 'mel', sh: 0, ...(i > 1 ? {sc: .7} : {})}, rp('hn', 'G1', i, 1.25),
    i < 2 ? {f: 56, t: 60, r: 'mel', sh: -12} : rp('hn', 'G2', i, 1.25),
    i % 2 ? CHROM(i === 1 ? 12 : 0) : rp('hn', 'G3a', i, 1.25), rp('hn', 'G3', i, 1.25), rp('hn', 'E', i, 1.25)];
  // ティンパニ（1回目）：G・A・D の3つを4分音符で軽く
  const POMP_TIMP = 'G G D D G G G G G G G G A A D D G G A A A A D D G G A A D D'.split(' ')
    .map((x, k) => ({i: 'timp', b: k, m: nn(x + (x === 'D' ? '3' : '2')), v: k % 2 ? .1 : .12}));
  // ティンパニ（全合奏）：G・C・D の3つを4分音符で。1小節に1文字（17〜28小節目、30〜38小節目）。29小節目はロール
  const TIMP_M = {G: nn('G2'), C: nn('C3'), D: nn('D3')};
  const timpBars = (s, from) => [...s].flatMap((x, k) => [from + 2 * k, from + 1 + 2 * k].map(b => ({i: 'timp', b, m: TIMP_M[x], v: b === 32 ? .7 : b % 2 ? .32 : .4})));
  // 打楽器の毎拍の型：大太鼓とシンバルは2拍目を少し軽く、スネアは前打音（2つの小さな音。短いロールで打つ）をつけて
  const onBeats = (from, to, fn) => each(from, to, 1, b => fn(b, b % 2 === 0));
  const drag = (b, v) => [{i: 'sd', b: b - .15, d: .15, roll: true, v: v * .4, v1: v * .65}, {i: 'sd', b, v}];

