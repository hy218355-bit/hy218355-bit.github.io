    // つなぎの駆け上がり（pesante）と、半音で下がる線（テヌート）は1音ずつ
    slur: [[0, 'bar'], [30, 'tongue'], [32, 'bar'], [60, 'tongue'], [64, 'bar']],
    scale: [[0, [0, 2, 4, 6, 7, 9, 11]]],
    mel: POMP_MEL,
    chords: chords(POMP_CH),
    bass: POMP_BASS,
    lines: {ped: POMP_PED, run: POMP_RUN, runLo: POMP_RUN_LO, chrom: POMP_CHROM, chromVc: POMP_CHROM_VC},
    // 1回目は p（10小節目で < >、14小節目で >）。16小節目は駆け上がりで一気に大きくして sf。
    // 全合奏は ff（17小節目に rf）、27〜28小節目で cresc. して29小節目の山場へ、31〜32小節目のロールで33小節目の sf へ、
    // 37〜38小節目のロールでもう一度大きくして終わる
    dyn: [[0,.36],[18,.36],[19.5,.44],[20,.4],[26,.42],[28,.36],[30,.4],[31.5,.74],[31.9,.82],[32,.96],[36,.92],[52,.92],[55.9,.97],[56,.98],[60,.95],
      [63.9,1],[64,1],[66,.94],[72,.92],[73.9,1],[74,1],[80,1]],
    // 楽譜の上のテンポの変わり目：16小節目 poco allargando、29小節目 allargando、34小節目から rit.（1拍の長さの倍率）
    tcurve: [[0,1],[30,1],[31.9,1.1],[32,1],[56,1],[58,1.08],[66,1.08],[72,1.14],[76,1.2],[80,1.22]],
    // 解釈の揺れ：フレーズの終わりで少し息をとり、最後の和音はたっぷりのばす
