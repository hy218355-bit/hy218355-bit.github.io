'use strict';
/* 副顧問・朝野先生。部の今の状態だけを見て話し、能力や保存内容は変えない。 */
function advisorHint(s, lineup = false){
  const hint = (key, line, text) => ({key, line, text});
  if(recruitsDue(s) && !s.pending) return hint('intake',
    s.members.length ? '新しい仲間の楽器、一緒に考えましょう。' : '最初の5人。まずは楽器を決めましょう。',
    '副顧問の朝野です。一緒に、この部を育てましょう。顔を押すと、希望の楽器と経験が見られます。初めは「この配置で決める」でも安心です。あとで部員カードから席を移せます。');
  if(s.phase === 'choose') return hint('choose', '好きな曲を、今の部に合う難しさで。',
    '星が多い曲ほど、譜読みに時間がかかります。初めは星の少ない曲もおすすめ。「お手本」と「いまの部で」を聴き比べて、育てたい音を探しましょう。基礎の力が育つと、新しい曲も早く読めるようになります。');
  if(s.phase === 'chooseSet') return hint('set', '今年は2曲。練習の時間を分けましょう。',
    '課題曲と自由曲は、別々に譜読みが必要です。今週の練習で配分を変えられます。まだ読めていない曲に時間をかけて、最後は合奏で合わせましょう。');
  if(s.phase === 'end' || s.phase === 'winter') return hint('year', '4月の音と、今の音。聴いてみませんか。',
    '日誌に、本番の録音が残っています。点数だけでなく、一人ひとりの音や成長も聴いてみましょう。冬は新しい部で練習し、3月にこの1年をふり返ります。');
  const ev = eventAt(s, s.week);
  if(s.pending){
    if(!s.pending.revealed) return hint('playing', 'お疲れさま。まずは演奏を聴きましょう。',
      '本番の結果を見たあとも、録音は聴き返せます。部員の顔を押すと、その人の音も聴けますよ。');
    if(s.pending.kind === 'concert') return hint('concert', '今日の音が、次の練習の出発点です。',
      '初めから上手でなくても心配いりません。録音を聴き、合奏で気になったところを次の練習へつなげましょう。演奏会の出来は、大会の審査点とは別です。');
    return hint('result', '結果は一つの目安。次に育てる力を探しましょう。',
      '講評と録音を合わせて見てみましょう。音程やリズムは基礎練習、譜読みは曲の練習、部のまとまりは合奏で育ちます。人選で控えにした子も、毎週の練習で育ちます。');
  }
  if(lineup || (ev?.kind === 'audition' && s.audition && !s.audition.decided)) return hint('lineup',
    '安定した音が増えるほど、響きは厚くなります。',
    '人数だけでは決まりません。不安定な音が重なると全体も乱れますが、育った子が増えるほど厚みになります。「おすすめ」を出発点に、顔を選び直して音と予想を比べましょう。控えの子も練習で育つので、次の舞台を目指せます。');
  if(ev?.kind === 'concert' || ev?.kind === 'contest') return hint('stage', '舞台袖では、緊張している子にひと声を。',
    '顔のようすを見て、声をかけたり、全員で深呼吸したりできます。指揮は演奏を助けますが、主役は練習で育てた部員の力です。初めは聴くだけでも安心です。');
  if(ev?.kind === 'forced') return hint('test', 'テストの週は、休む時間にもなりますね。',
    '今週はテスト勉強です。体力が戻るので、次の練習のことも考えておきましょう。');
  if(foundingYear(s) && s.week === 0) return hint('first-practice', 'まずは5人で、音を合わせてみましょう。',
    '「この内容で1週間すすめる」で練習できます。初めての本番は来週。まだ上手でなくても、今日の音が育つ出発点になりますよ。');
  if(s.episode || s.consult || s.outing) return hint('story', '部員の話を聞くのも、大切な時間です。',
    '相談や行事も、その子の得意なことや思い出につながります。練習を進めると流れるので、気になる話は先に聞いてみましょう。');
  const ms = seated(s);
  if(s.members.length && s.members.every(m => planFor(s, m) === 'rest')) return hint('rest-plan',
    'ひと休みして、次の音につなげましょう。',
    '今週は休む予定ですね。体力とやる気を戻して、次の練習や本番に備えましょう。「休む」の方針は1週だけで、次の週は「おまかせ」に戻ります。');
  if(ms.some(m => (m.sta ?? 100) < 30)) return hint('rest', '疲れた子は、今週ひと休みさせましょう。',
    '疲れたままだと練習の効果が落ちます。体力の低い子の顔を押して「休む」を選べます。一人ずつ休ませられますよ。');
  if(stageIn(s, 1)?.w === 1 && s.members.length){
    // 今選んでいる練習の消費量と毎週の回復だけを見る。来週の出来事や調子は先読みしない。
    const stamina = s.members.reduce((v, m) => {
      const mu = MENU_BY[planFor(s, m)];
      const cost = mu.cost > 0 ? mu.cost * (ev?.costMult || 1) * (1 - SKILLS.tough.cost * skillLv(m, 'tough')) : mu.cost;
      return v + clamp(clamp((m.sta ?? s.stamina) - cost, 0, 100) + 6, 0, 100);
    }, 0) / s.members.length;
    if(stamina < 50) return hint('before-rest', '来週の本番へ、体力も残しましょう。',
      'このままの練習だと、本番で疲れが残りそうです。体力の少ない子を今週休ませると、育った力を出しやすくなります。顔の横から練習を選べますよ。');
  }
  if(s.policy === 'basics') return hint('basics', '基礎の成果は、合奏でも確かめましょう。',
    '基礎が育つと、音が安定し、新しい曲の譜読みも早くなります。ただ、基礎だけでは部のまとまりは育ちません。曲の練習や合奏も間に入れて、育った力を音楽につなげましょう。');
  if(s.pieceId && ms.length){
    const rd = readAvg(s, s.pieceId);
    if(rd < 60) return hint('reading', '新しい曲は、まず自分の譜面から。',
      '顔の横の練習を押して「曲の練習」を選ぶと、譜読みがよく進みます。部員カードで、まだ慣れていない区間も見られます。上手な子ほど早く読めますが、星の多い曲には時間をかけましょう。');
    if(s.cohesion < 60) return hint('together', '読めてきましたね。今度はみんなで合わせましょう。',
      '一人で読めることと、みんなで合わせられることは別です。個人練習で譜読みが止まってきたら合奏へ。参加する人が多いほど、部のまとまりが育ちます。');
  }
  return hint('practice', '苦手な力を、一人ずつ育てていきましょう。',
    '音程はチューニング、リズムはメトロノーム、音色はロングトーン。基礎が弱いうちは、この3つを先に。安定したらフレーズ練習で表現へ。「おまかせ」を土台に、その子の練習を顔の横から選べます。育った音は合奏で聴けますよ。');
}
